#!/usr/bin/env python
"""Generate results/day1_notes.md from measured evidence only."""
import json
from pathlib import Path

NR = "NOT RUN"


def load(p):
    f = Path(p)
    return json.loads(f.read_text()) if f.exists() else {}


env, aud, ex = load("results/day1_env.json"), load("results/day1_dataset_audit.json"), load("results/day1_audit_extra.json")
ig, dp, io = load("results/day1_integrity.json"), load("results/day1_cross_split_duplicates.json"), load("results/day1_io_bench.json")
e = env.get("_env", {})
steps = {k: v for k, v in env.items() if not k.startswith("_")}
groups = aud.get("groups", {})
L = ["# Day 1 notes (generated by scripts/day1_make_notes.py from measured evidence)", ""]

L += ["## Environment",
      f"- Python {e.get('python', NR)} | torch {e.get('torch', NR)} | torchvision {e.get('torchvision', NR)} | CUDA build {e.get('cuda_build', NR)} | driver {e.get('driver', NR)}",
      f"- Device: {steps.get('device', {}).get('detail', NR)}",
      f"- Smoke tests: {sum(v['status'] == 'PASS' for v in steps.values())}/{len(steps)} PASS", ""]

L += ["## Splits (official, unmodified)", "| Group | Images | Patients | Masks |", "|---|---|---|---|"]
for k, g in groups.items():
    L.append(f"| {k} | {g.get('n_images')} | {g.get('n_patients_parsed')} | {g.get('n_masks', '-')} |")
L += ["", f"- Patient overlap: {aud.get('patient_overlap_counts', NR)}", f"- Audit warnings: {aud.get('warnings', NR)}", ""]

tr = groups.get("train/good", {})
st = tr.get("image_stats", {})
c = ex.get("image_colour")
L += ["## Image and mask encoding",
      f"- Image size/mode (train/good): {tr.get('size_mode_counts', NR)}",
      f"- Sampled train images with R==G==B: {st.get('n_rgb_channels_identical', NR)} of {st.get('n_sampled', NR)}"]
if c:
    n = c["n_unique_rgb_triples_overall"]
    L.append(f"- Colour structure ({c['n_images_sampled']} sampled images): {n} unique RGB triples; top-256 triples cover "
             f"{c['frac_pixels_in_top256_triples']:.4f} of pixels; median {c['median_unique_triples_per_image']} unique per image; "
             f"mean pure-black fraction {c['mean_frac_pure_black_pixels']:.3f}")
    L.append("- Reading: <=256 unique triples suggests a lookup-table rendering (test intensity recovery on Day 2)."
             if n <= 256 else "- Reading: >256 unique triples: treat the 3 channels as data; do not assume a recoverable single intensity.")
else:
    L.append(f"- Colour structure: {NR}")
for k in ("valid/Ungood", "test/Ungood"):
    ms = groups.get(k, {}).get("mask_stats", {})
    L.append(f"- {k} mask RGB values: {ms.get('rgb_values_union_first12', NR)}; empty masks: {ms.get('n_empty_masks', NR)}")
L += ["- Foreground rule: any RGB channel != 0 (alpha ignored); nearest-neighbour for masks.", ""]

L += ["## Lesion size and slice position"]
for k in ("valid/Ungood", "test/Ungood"):
    a = ex.get(f"mask_area_px__{k}")
    L.append(f"- {k} lesion px (p5/25/50/75/95): {a['pct_5_25_50_75_95']} | min {a['min']} max {a['max']} | "
             f"<10px: {a['lt_10px']}, <50px: {a['lt_50px']}, <100px: {a['lt_100px']} of {a['n']}" if a else f"- {k}: {NR}")
si = ex.get("slice_index")
if si:
    L += ["", "| Group | slice min | slice max | slice mean |", "|---|---|---|---|"]
    for k, v in si.items():
        L.append(f"| {k} | {v['min']} | {v['max']} | {v['mean']:.1f} |")
    d = si["test/Ungood"]["mean"] - si["test/good"]["mean"]
    L.append(f"\n- Mean slice index, test/Ungood minus test/good: {d:+.1f} (a large gap means slice position may confound image-level scores; check Day 2)")
L.append("")

L += ["## Integrity and leakage",
      f"- Files hashed: {ig.get('n_files_hashed', NR)}; corrupt/zero-byte: {ig.get('corrupt_or_zero_byte', {}).get('count', NR)}; "
      f"identical-pixel groups inside a split: {ig.get('identical_pixels_within_split', {}).get('groups', NR)}",
      f"- Identical-pixel groups across splits: {ig.get('identical_pixels_across_splits', {}).get('groups', NR)} (valid/Ungood <-> test/Ungood)"]
if dp:
    r = dp["rows"][0]
    L += [f"- Duplicates: {dp['n_shared_filenames']} shared filenames; image-identical {dp['n_image_identical']}; mask-identical {dp['n_mask_identical']}; "
          f"= {dp['frac_of_valid_Ungood']:.1%} of valid/Ungood, {dp['frac_of_test_Ungood']:.2%} of test/Ungood",
          f"- Same patients, different slices (example {r['file']}): valid {r['valid_Ungood_slices']} vs test {r['test_Ungood_slices']}"]
L += ["- Train is disjoint from valid and test; official splits unmodified. Plan: official test metrics plus a patient-disjoint "
      "sensitivity run (50 test images excluded; see configs/data.yaml).", ""]

L += ["## I/O", f"- {io or NR}", "", "## Open decisions for Day 2/3",
      "- Image channel handling (RGB as data vs recovered intensity)", "- Brain-only vs full-frame pixel metrics",
      "- Reporting of tiny lesions", "- Patient-disjoint sensitivity evaluation (50 images)", "",
      "Evidence: results/day1_*.json, results/day1/, results/day1_git_check.txt"]
Path("results/day1_notes.md").write_text("\n".join(L) + "\n")
print("\n".join(L))

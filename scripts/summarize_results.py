"""Write docs/RESULTS.md from the saved metrics files. No number is typed by hand.

    python scripts/summarize_results.py [--root .] [--out docs/RESULTS.md]
Reads artifacts/models/<run>/metrics_{valid,test}.json, threshold.json and results/model_selection.json.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

MAIN = ["autoencoder_s0", "padim_s0", "patchcore_s0"]


def _j(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def f(v, n=3):
    return "n/a" if v is None else f"{v:.{n}f}"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=".")
    ap.add_argument("--out", default="docs/RESULTS.md")
    a = ap.parse_args(argv)
    root = Path(a.root)
    M = {r: {s: _j(root / "artifacts/models" / r / f"metrics_{s}.json") for s in ("valid", "test")} for r in MAIN}
    sel = _j(root / "results/model_selection.json") or {}
    L = ["# Measured results (generated by `scripts/summarize_results.py` from saved metrics files)", "",
         "BMAD Brain (BraTS 2021 FLAIR, 240x240). Thresholds frozen on `valid` (83 images), test evaluated once per model. "
         "Research flags for qualified human review, not diagnosis.", ""]
    if sel:
        L += [f"Selected on validation only: **{sel.get('selected')}** (rule: gates VRAM<=6 GB, latency<=1000 ms; within 0.02 AUPRO of best; "
              "then best mean rank of pixel AUROC, per-image Dice, image AUROC).", ""]
    L += ["## Test split, all three models (3,715 images: 640 normal, 3,075 abnormal)", "",
          "| Model | Image AUROC [95% patient-bootstrap CI] | Pixel AUROC (full frame) | Pixel AUROC (brain ROI) | AUPRO full / ROI | Dice per-image | Dice pooled | Latency ms | Ckpt MB |",
          "|---|---|---|---|---|---|---|---|---|"]
    for r in MAIN:
        t = M[r]["test"]
        if not t:
            L.append(f"| {r} | NOT RUN |||||||| "); continue
        o, e = t["official"], t["engineering"]
        ci = o["image"].get("image_auroc_ci95_patient_bootstrap")
        L.append(f"| {r} | {f(o['image']['image_auroc'])} [{f(ci[0])}, {f(ci[1])}] | {f(o['pixel_full_frame']['pixel_auroc'])} | "
                 f"{f(o['pixel_brain_roi']['pixel_auroc'])} | {f(o['pixel_full_frame']['aupro_fpr0.3'])} / {f(o['pixel_brain_roi']['aupro_fpr0.3'])} | "
                 f"{f(o['pixel_full_frame']['dice_per_image'])} | {f(o['pixel_full_frame']['dice_pooled'])} | "
                 f"{f(e['latency_ms_mean'], 1)} | {f(e['checkpoint_mb'], 1)} |")
    L += ["", "Pixel metrics: the full-frame numbers include the easy black background; the brain-ROI numbers are the honest ones to quote for localisation.", ""]
    L += ["## Image-level operating point at the validation-frozen threshold (test)", "",
          "| Model | Threshold | Sensitivity | Specificity | FPR | Precision | F1 |", "|---|---|---|---|---|---|---|"]
    for r in MAIN:
        t = M[r]["test"]
        if t:
            i = t["official"]["image"]
            L.append(f"| {r} | {f(i['img_threshold'], 4)} | {f(i['img_sensitivity'])} | {f(i['img_specificity'])} | {f(i['img_fpr'])} | {f(i['img_precision'])} | {f(i['img_f1'])} |")
    L += ["", "Precision is high mainly because 83% of test images are abnormal; use sensitivity/specificity.", ""]
    for r in MAIN:
        t = M[r]["test"]
        if not t:
            continue
        L += [f"## Robustness variants ({r}, test)", "", "| Variant | n | Image AUROC | Pixel AUROC | AUPRO |", "|---|---|---|---|---|"]
        o = t["official"]
        L.append(f"| all images | {t['n_images']} | {f(o['image']['image_auroc'])} | {f(o['pixel_full_frame']['pixel_auroc'])} | {f(o['pixel_full_frame']['aupro_fpr0.3'])} |")
        w = t.get("without_lesions_under_100px")
        if w:
            L.append(f"| lesions <100 px removed | {w['n_images']} | n/a | {f(w['pixel_full_frame']['pixel_auroc'])} | {f(w['pixel_full_frame']['aupro_fpr0.3'])} |")
        p = t.get("patient_disjoint")
        if p:
            L.append(f"| patient-disjoint (drops {p['n_excluded']} shared-patient images) | {p['n_images']} | {f(p['image']['image_auroc'])} | {f(p['pixel_full_frame']['pixel_auroc'])} | {f(p['pixel_full_frame']['aupro_fpr0.3'])} |")
        L += ["", "Slice-position-stratified image AUROC (guards against the slice-position confound):", "",
              "| Slice band | normal | abnormal | Image AUROC |", "|---|---|---|---|"]
        for band, s in (t.get("slice_stratified_image") or {}).items():
            note = " (too few normals to interpret)" if s["n_normal"] < 30 else ""
            L.append(f"| {band} | {s['n_normal']} | {s['n_abnormal']} | {f(s['image_auroc'])}{note} |")
        L.append("")
    L += ["## Validation split (used for selection and thresholds; 83 images, wide uncertainty)", "",
          "| Model | Image AUROC | Pixel AUROC | AUPRO | Dice per-image |", "|---|---|---|---|---|"]
    for r in MAIN:
        v = M[r]["valid"]
        if v:
            o = v["official"]
            L.append(f"| {r} | {f(o['image']['image_auroc'])} | {f(o['pixel_full_frame']['pixel_auroc'])} | {f(o['pixel_full_frame']['aupro_fpr0.3'])} | {f(o['pixel_full_frame']['dice_per_image'])} |")
    out = root / a.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
